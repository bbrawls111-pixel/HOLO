/*
 * Слой БД. На Vercel — Neon Postgres, локально — PGlite (тот же Postgres в процессе).
 * В SQL используются плейсхолдеры «?» — они превращаются в $1, $2…
 */

let driver = null;
let readyPromise = null;

const toPg = (sql) => {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
};

async function createNeonDriver() {
  const { Pool, Client, neonConfig, types } = await import('@neondatabase/serverless');
  const { default: WebSocket } = await import('ws');
  neonConfig.webSocketConstructor = WebSocket;
  types.setTypeParser(20, (v) => Number(v)); // BIGINT → number (метки времени, seq)

  const pool = new Pool({ connectionString: config.databaseUrl, max: 4 });
  pool.on('error', (err) => console.error('[db pool]', err.message));

  return {
    query: async (text, params) => (await pool.query(text, params)).rows,
    async tx(fn) {
      const c = await pool.connect();
      try {
        await c.query('BEGIN');
        const result = await fn(async (t, p) => (await c.query(t, p)).rows);
        await c.query('COMMIT');
        return result;
      } catch (err) {
        await c.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        c.release();
      }
    },
    async listen(channel, onPayload) {
      const client = new Client({ connectionString: config.databaseUrlUnpooled });
      client.on('notification', (m) => onPayload(m.payload));
      await client.connect();
      await client.query(`LISTEN ${channel}`);
      return {
        closed: new Promise((resolve) => {
          client.on('error', resolve);
          client.on('end', resolve);
        }),
        close: () => client.end().catch(() => {}),
      };
    },
  };
}

async function createLocalDriver() {
  fs.mkdirSync(config.localDbDir, { recursive: true });
  const modName = '@electric-sql/pglite'; // динамически: на Vercel не нужен
  const { PGlite } = await import(modName);
  const pg = new PGlite(config.localDbDir, { parsers: { 20: (v) => Number(v) } });
  await pg.waitReady;
  return {
    query: async (text, params) => (await pg.query(text, params)).rows,
    tx: (fn) => pg.transaction((t) => fn(async (text, params) => (await t.query(text, params)).rows)),
    async listen(channel, onPayload) {
      const unsub = await pg.listen(channel, onPayload);
      return { closed: new Promise(() => {}), close: () => unsub() };
    },
  };
}

