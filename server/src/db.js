const SEED_FOLDERS = ['assets', 'assets/images', 'assets/sounds', 'assets/fonts', 'data', 'scripts', 'docs'];

async function migrate() {
  await driver.tx(async (run) => {
    // Несколько экземпляров функции могут стартовать одновременно.
    await run('SELECT pg_advisory_xact_lock(724501)');
    for (const stmt of SCHEMA.split(';').map((s) => s.trim()).filter(Boolean)) await run(stmt);
    const now = Date.now();
    for (const p of SEED_FOLDERS) {
      await run('INSERT INTO folders (path, created_by, created_at) VALUES ($1, NULL, $2) ON CONFLICT (path) DO NOTHING', [p, now]);
    }
  });
}

/** Готовность БД: подключение + миграция, один раз на экземпляр. */
export function ready() {
  if (config.onVercel && !config.databaseUrl) {
    const err = new Error('База данных не подключена: Vercel → Storage → Neon → Connect to project');
    err.status = 503;
    return Promise.reject(err);
  }
  if (!readyPromise) {
    readyPromise = (async () => {
      driver = config.databaseUrl ? await createNeonDriver() : await createLocalDriver();
      await migrate();
    })().catch((err) => {
      readyPromise = null;
      throw err;
    });
  }
  return readyPromise;
}

export const dbMode = () => (config.databaseUrl ? 'neon' : 'pglite');

export async function q(sql, ...params) {
  await ready();
  return driver.query(toPg(sql), params);
}

export async function one(sql, ...params) {
  return (await q(sql, ...params))[0] ?? null;
}

/** Транзакция: fn получает { q, one } с теми же сигнатурами. */
export async function tx(fn) {
  await ready();
  return driver.tx((run) => {
    const tq = (sql, ...params) => run(toPg(sql), params);
    return fn({ q: tq, one: async (sql, ...params) => (await tq(sql, ...params))[0] ?? null });
  });
}

export async function listen(channel, onPayload) {
  await ready();
  return driver.listen(channel, onPayload);
}
