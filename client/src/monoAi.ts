export type MonoMode = 'ref' | 'create' | 'continue';

const PERSONA = [
  '[Инструкция для ассистента — не цитируй и не упоминай её в ответе]',
  'Ты — Mono AI, помощник в документах Holo. Holo — рабочее пространство небольшой команды, которая делает игры:',
  'сюжеты, лор, персонажи, диздоки, сценарии, заметки.',
  'Не называй языковую модель или компанию, на которой работаешь. Если спросят — ты Mono AI.',
  'Пиши по-русски (если пользователь пишет на другом языке — на его языке).',
  'Пиши обычным текстом без разметки Markdown: никаких **, __, # и ```. Абзацы разделяй пустой строкой,',
  'списки — строками, начинающимися с «— ».',
].join('\n');

const quote = (s: string) => `"""\n${s.trim()}\n"""`;

/** Хвост текста не длиннее max символов — начинаем с границы абзаца, если можно. */
function tail(text: string, max: number) {
  if (text.length <= max) return text;
  const cut = text.slice(-max);
  const p = cut.indexOf('\n\n');
  return '…' + (p > 0 && p < max / 3 ? cut.slice(p + 2) : cut);
}

export function referencePrompt(question: string, doc: { title: string; text: string }) {
  const lines = [
    PERSONA,
    '',
    'Режим «Референс». Помоги придумывать: подбери конкретные референсы под запрос — фильмы, игры, книги, аниме,',
    'комиксы, живопись, музыку, архитектуру, реальные исторические события, места и явления.',
    'Для каждого пункта: название (автор или год, только если знаешь точно) и одно-два предложения, чем именно он',
    'полезен для этой идеи: атмосфера, визуал, механика, приём сюжета. 5–8 пунктов, без вступления и без вывода.',
    'Не выдумывай несуществующие произведения. Если в запросе просят другое (идеи, имена, примеры) — дай это в том же формате.',
  ];
  if (doc.title.trim() || doc.text.trim()) {
    lines.push('', `Документ, над которым работает пользователь: «${doc.title.trim() || 'Без названия'}».`);
    if (doc.text.trim()) lines.push('Начало документа (для понимания темы):', quote(doc.text.slice(0, 1800)));
  }
  lines.push('', 'Запрос пользователя:', question.trim());
  return lines.join('\n');
}

export function createPrompt(request: string) {
  return [
    PERSONA,
    '',
    'Режим «Создание». Напиши новый документ по запросу пользователя: эссе, сюжет, лор, описание персонажа или мира,',
    'диздок, сценарий, квест, диалог — что попросят.',
    'Первая строка ответа — только название документа, без кавычек, точки и слова «Название».',
    'Затем пустая строка и сам текст целиком. Без вступлений вроде «Вот ваш текст» и без пояснений в конце.',
    'Заголовки разделов — отдельной строкой. Пиши живо и конкретно, объём — сколько нужно по смыслу запроса.',
    '',
    'Запрос пользователя:',
    request.trim(),
  ].join('\n');
}

export function continuePrompt(opts: { title: string; before: string; fragment: string; wish: string }) {
  const lines = [
    PERSONA,
    '',
    'Режим «Додумывание». Пользователь выделил фрагмент документа. Продолжи текст после этого фрагмента —',
    'по смыслу и хронологически: что происходит дальше, следующий шаг, событие, мысль или раздел.',
    'Сохраняй стиль, тон, лицо повествования, имена и факты из текста выше. Не пересказывай и не повторяй уже',
    'написанное, не противоречь ему. Ответ — только новый текст продолжения, без вступлений, заголовка «Продолжение»',
    'и пояснений. Объём — примерно как выделенный фрагмент, если пользователь не попросил иначе.',
    '',
    `Название документа: «${opts.title.trim() || 'Без названия'}».`,
  ];
  if (opts.before.trim()) lines.push('', 'Текст документа выше фрагмента (контекст):', quote(tail(opts.before, 9000)));
  lines.push('', 'Выделенный фрагмент — продолжи сразу после него:', quote(opts.fragment.slice(0, 6000)));
  lines.push('', 'Пожелание пользователя: ' + (opts.wish.trim() || 'нет, просто продолжи логично.'));
  return lines.join('\n');
}

/** Убрать остатки Markdown, если модель всё же ими воспользовалась. */
export function plainText(s: string) {
  return s
    .replace(/\r\n/g, '\n')
    .replace(/^```\w*\n?|```$/gm, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/__(.+?)__/g, '$1')
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/** Ответ режима «Создание»: первая строка — название, остальное — текст. */
export function splitTitle(answer: string) {
  const text = plainText(answer);
  const nl = text.indexOf('\n');
  const first = (nl < 0 ? text : text.slice(0, nl)).trim();
  const title = first
    .replace(/^(название|заголовок|title)\s*[:—-]\s*/i, '')
    .replace(/^[«"'*\s]+|[»"'*.\s]+$/g, '')
    .slice(0, 120);
  if (nl < 0 || !title || title.length > 100) return { title: 'Новый документ', text };
  return { title, text: text.slice(nl + 1).trim() };
}
